"""One-slide summary of SemStamp on all our generators (beamer frame), in the format of the earlier slide but per model.
Values = mean over the three datasets of a benchmark, computed from runs/*.json and the generation records via
scripts/semstamp_tables.py.  Writes docs/semstamp_slide.tex."""

import statistics as S
import sys
from pathlib import Path

sys.path.insert(0, "scripts"); sys.path.insert(0, ".")
from semstamp_tables import J, OB, SP, cost, judge, tpr  # noqa: E402

M = [("llama3b", "3B"), ("llama1b", "1B"), ("qwen08b", "Qwen")]


def runs(bench):
    out = []
    for kind in ("base", "chat"):
        for m, short in M:
            if kind == "chat":
                if bench == "sp":
                    run = f"sp_bench_{m}_nl" if m == "qwen08b" else f"sp_bench_{m}"
                    det = f"runs/sp_detect_{m}_nl.json" if m == "qwen08b" else f"runs/sp_detect_{m}.json"
                    jd = None if m == "qwen08b" else SP
                else:
                    run = {"llama3b": "ob_bench", "llama1b": "ob_bench_llama1b", "qwen08b": "ob_bench_qwen08b_nl"}[m]
                    det = {"llama3b": "runs/ob_detect_ob_bench_refill.json", "llama1b": "runs/ob_detect_ob_bench_llama1b_refill.json",
                           "qwen08b": "runs/ob_detect_ob_bench_qwen08b_nl.json"}[m]
                    jd = None
            else:
                b = "sp_bench" if bench == "sp" else "ob_bench"
                run = f"{b}_{m}_base_nl" if m == "qwen08b" else f"{b}_{m}_base"
                det = (f"runs/sp_detect_{m}_base_nl.json" if m == "qwen08b" else f"runs/sp_detect_{m}_base.json") if bench == "sp" else \
                      (f"runs/ob_detect_ob_bench_{m}_base_nl.json" if m == "qwen08b" else f"runs/ob_detect_ob_bench_{m}_base.json")
                jd = None
            out.append((kind, short, run, det, jd))
    return out


def mean_tpr(res, run, doms, key="z_chain:human_1%", suf=""):
    v = [tpr(res, run + suf, d, key) for d in doms]
    return None if any(x is None for x in v) else S.mean(v)


def main():
    cols = [("sp", SP) + c for c in runs("sp")] + [("ob", OB) + c for c in runs("ob")]
    data = []
    for bench, doms, kind, short, run, det, jd in cols:
        res = (J(det) or {}).get("results", {})
        c = cost(run, doms)
        data.append({"t1": mean_tpr(res, run, doms), "t01": mean_tpr(res, run, doms, "z_chain:human_0.1%"),
                     "pl": mean_tpr(res, run, doms, suf="_para_light"), "ps": mean_tpr(res, run, doms, suf="_para_strong"),
                     "j": judge(run, "semstamp", jd), "jn": judge(run, "clean_seed1", jd),
                     "cand": c["cand"], "gu": c["giveup"], "sec": c["sec"]})
    weak = {"t1": lambda v, d: v < 80, "t01": lambda v, d: v < 60, "pl": lambda v, d: v < 50, "ps": lambda v, d: v < 50,
            "j": lambda v, d: d["jn"] is not None and v < d["jn"] - 0.03, "cand": lambda v, d: v > 30, "gu": lambda v, d: v > 15}
    fmt = {"t1": "{:.0f}\\%", "t01": "{:.0f}\\%", "pl": "{:.0f}\\%", "ps": "{:.0f}\\%", "j": "{:.3f}", "cand": "{:.0f}", "gu": "{:.0f}\\%", "sec": "{:.0f}\\,s"}

    def cell(k, d):
        v = d[k]
        if v is None:
            return "--"
        s = fmt[k].format(v)
        if k == "j" and d["jn"] is not None:
            s += f" {{\\tiny({d['jn']:.3f})}}"
        return (r"\cellcolor{weak}\textcolor{weakink}{" + s + "}") if k in weak and weak[k](v, d) else s

    rows = [("t1", "Detection, 1\\% FPR", "TPR, no attack"), ("t01", "Detection, 0.1\\% FPR", "TPR, no attack, stricter FPR"),
            ("pl", "Light paraphrase", "TPR after a light paraphrase"), ("ps", "Strong paraphrase", "TPR after a strong paraphrase"),
            ("j", "Text quality", "LLM judge win rate (no-difference level)"),
            ("cand", "Tries per sentence", "candidate sentences drawn per kept sentence"),
            ("gu", "Sentences left unmarked", "gave up after 100 tries"), ("sec", "Time per text", "one of 3 processes on an A100")]
    L = [r"% generated by scripts/semstamp_slide.py -- needs \usepackage{booktabs,colortbl,xcolor,makecell,graphicx}",
         r"\definecolor{weak}{HTML}{FBE3DA}\definecolor{weakink}{HTML}{B5401D}\definecolor{gapink}{HTML}{B5401D}",
         r"\begin{frame}{SemStamp is weaker on chat models, at low FPR, under paraphrase, and it is expensive to run}",
         r"\centering\scriptsize", r"\setlength{\tabcolsep}{3.5pt}", r"\renewcommand{\arraystretch}{1.15}",
         r"\resizebox{\textwidth}{!}{%", r"\begin{tabular}{l" + "c" * 6 + "|" + "c" * 6 + "}", r"\toprule",
         r" & \multicolumn{6}{c|}{RealNews, BookSum, Reddit-TIFU (SemStamp's datasets)} & \multicolumn{6}{c}{ArXiv, BookSum, Wikipedia (our benchmark)} \\",
         r" & \multicolumn{3}{c}{Base model} & \multicolumn{3}{c|}{Chat model} & \multicolumn{3}{c}{Base model} & \multicolumn{3}{c}{Chat model} \\",
         r"\cmidrule(lr){2-4}\cmidrule(lr){5-7}\cmidrule(lr){8-10}\cmidrule(lr){11-13}",
         r"\textbf{What we measure} & " + " & ".join(rf"\textbf{{{short}}}" for (_, _, _, short, *_) in cols) + r" \\", r"\midrule"]
    for k, name, sub in rows:
        L.append(rf"\makecell[l]{{\textbf{{{name}}}\\[-1pt]{{\tiny {sub}}}}} & " + " & ".join(cell(k, d) for d in data) + r" \\")
        if k in ("ps", "j"):
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular}}", r"\\[4pt]",
          r"{\tiny Mean over the three datasets of each benchmark (1,000 prompts each for SemStamp's datasets, 500 for ours; 200 "
          r"tokens per text). 3B / 1B = Llama-3.2-3B / -1B, Qwen = Qwen3.5-0.8B; chat models get a one-line continuation instruction, "
          r"base models continue the text. Thresholds from human-written continuations. Shaded: TPR below 80\% (1\% FPR), 60\% "
          r"(0.1\% FPR) or 50\% (paraphrase); judge more than 0.03 below its no-difference level; more than 30 tries per sentence; "
          r"more than 15\% of sentences unmarked.}",
          r"\\[3pt]\raggedright\small\textcolor{gapink}{\textbf{The gap:}} a watermark that is cheap, works on chat models, and survives paraphrasing.",
          r"\end{frame}", ""]
    Path("docs/semstamp_slide.tex").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
